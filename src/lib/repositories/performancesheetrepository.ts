import { supabase } from "@/lib/supabase/client";

import type {
  BuilderDocument,
} from "@/lib/types/builderdocument";

/* ==========================================================
   Types
========================================================== */

export type PerformanceSheetStatus =
  | "draft"
  | "published"
  | "archived";

export interface PerformanceSheetRecord {
  id: string;

  organization_id: string;

  sheet_key: string;

  name: string;

  status: PerformanceSheetStatus;

  version: number;

  document: BuilderDocument;

  created_at: string;

  updated_at: string;
}

/* ==========================================================
   Save Builder Document
========================================================== */

export async function saveBuilderDocument(
  organizationId: string,
  document: BuilderDocument,
  sheetId?: string
): Promise<PerformanceSheetRecord> {
  /*
   * Existing sheet:
   * only drafts may be edited.
   */
  if (sheetId) {
    const { data, error } = await supabase
      .from("performance_sheets")
      .update({
        document,
      })
      .eq(
        "id",
        sheetId
      )
      .eq(
        "organization_id",
        organizationId
      )
      .eq(
        "status",
        "draft"
      )
      .select()
      .single();

    if (error) {
      throw new Error(
        `Failed to save performance sheet: ${error.message}`
      );
    }

    return data as PerformanceSheetRecord;
  }

  /*
   * No sheet exists yet.
   *
   * Create Version 1 of a new logical
   * performance sheet.
   *
   * sheet_key is generated by PostgreSQL.
   */
  const { data, error } = await supabase
    .from("performance_sheets")
    .insert({
      organization_id:
        organizationId,

      name:
        "Performance Sheet",

      status:
        "draft",

      version:
        1,

      document,
    })
    .select()
    .single();

  if (error) {
    throw new Error(
      `Failed to create performance sheet: ${error.message}`
    );
  }

  return data as PerformanceSheetRecord;
}

