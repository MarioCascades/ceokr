/* ==========================================================
   Publish Performance Sheet
========================================================== */

export async function publishPerformanceSheet(
  organizationId: string,
  sheetId: string
): Promise<PerformanceSheetRecord> {
  /*
   * Only a draft can become published.
   *
   * Once published, saveBuilderDocument()
   * will no longer update this row because
   * that function explicitly requires
   * status = draft.
   */
  const { data, error } = await supabase
    .from("performance_sheets")
    .update({
      status:
        "published",
    })
    .eq(
      "id",
      sheetId
    )
    .eq(
      "organization_id",
      organizationId
    )
    .eq(
      "status",
      "draft"
    )
    .select()
    .single();

  if (error) {
    throw new Error(
      `Failed to publish performance sheet: ${error.message}`
    );
  }

  return data as PerformanceSheetRecord;
}

/* ==========================================================
   Create Draft Revision
========================================================== */

export async function createDraftRevision(
  organizationId: string,
  publishedSheetId: string
): Promise<PerformanceSheetRecord> {
  /*
   * Load the published version that will
   * become the basis of the new revision.
   */
  const {
    data: publishedSheet,
    error: loadError,
  } = await supabase
    .from("performance_sheets")
    .select("*")
    .eq(
      "id",
      publishedSheetId
    )
    .eq(
      "organization_id",
      organizationId
    )
    .eq(
      "status",
      "published"
    )
    .single();

  if (loadError) {
    throw new Error(
      `Failed to load published performance sheet: ${loadError.message}`
    );
  }

  const source =
    publishedSheet as PerformanceSheetRecord;

  /*
   * Find the highest existing version for
   * this logical performance sheet.
   *
   * We do not assume source.version + 1,
   * because additional historical versions
   * may already exist.
   */
  const {
    data: latestVersion,
    error: versionError,
  } = await supabase
    .from("performance_sheets")
    .select(
      "version"
    )
    .eq(
      "organization_id",
      organizationId
    )
    .eq(
      "sheet_key",
      source.sheet_key
    )
    .order(
      "version",
      {
        ascending: false,
      }
    )
    .limit(1)
    .single();

  if (versionError) {
    throw new Error(
      `Failed to determine next performance sheet version: ${versionError.message}`
    );
  }

  const nextVersion =
    latestVersion.version + 1;

  /*
   * Create a new draft row.
   *
   * Same sheet_key:
   * same logical performance sheet.
   *
   * New id:
   * new immutable version.
   */
  const { data, error } = await supabase
    .from("performance_sheets")
    .insert({
      organization_id:
        organizationId,

      sheet_key:
        source.sheet_key,

      name:
        source.name,

      status:
        "draft",

      version:
        nextVersion,

      document:
        source.document,
    })
    .select()
    .single();

  if (error) {
    throw new Error(
      `Failed to create draft revision: ${error.message}`
    );
  }

  return data as PerformanceSheetRecord;
}

